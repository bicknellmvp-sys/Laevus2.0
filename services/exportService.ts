// Export Service for LAEVUS: Audio (.MP3) and Document (.DOC / .PDF) Exports

export interface ExportMessage {
  role: 'user' | 'model' | 'oracle' | string;
  text: string;
  timestamp?: Date | string;
}

export interface ExportPayload {
  title: string;
  persona?: string;
  messages: ExportMessage[];
  readingType?: string;
  userVoiceMode?: 'actual' | 'cloned' | 'default';
  date?: string;
}

// 1. Export as Microsoft Word Document (.DOC)
export const exportToWordDoc = (payload: ExportPayload): void => {
  const dateStr = payload.date || new Date().toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  const formattedConversation = payload.messages
    .map((msg) => {
      const isUser = msg.role === 'user';
      const sender = isUser ? 'User' : payload.persona || 'Oracle';
      const time = msg.timestamp
        ? new Date(msg.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
        : '';
      const bg = isUser ? '#f4f4f5' : '#fafafa';
      const border = isUser ? '#71717a' : '#dc143c';

      return `
        <div style="margin-bottom: 16px; padding: 12px 16px; background-color: ${bg}; border-left: 4px solid ${border}; border-radius: 4px; font-family: 'Segoe UI', Arial, sans-serif;">
          <div style="font-size: 11px; font-weight: bold; text-transform: uppercase; color: #52525b; margin-bottom: 6px;">
            ${sender} ${time ? '— ' + time : ''}
          </div>
          <div style="font-size: 14px; line-height: 1.6; color: #18181b; white-space: pre-wrap;">
            ${escapeHtml(msg.text)}
          </div>
        </div>
      `;
    })
    .join('');

  const docHtml = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>${escapeHtml(payload.title)}</title>
      <style>
        body {
          font-family: 'Segoe UI', Helvetica, Arial, sans-serif;
          margin: 40px;
          color: #18181b;
          line-height: 1.6;
        }
        h1 {
          font-size: 24px;
          color: #09090b;
          margin-bottom: 4px;
        }
        .meta {
          font-size: 12px;
          color: #71717a;
          margin-bottom: 24px;
          border-bottom: 1px solid #e4e4e7;
          padding-bottom: 12px;
        }
        .footer {
          margin-top: 40px;
          font-size: 11px;
          color: #a1a1aa;
          text-align: center;
          border-top: 1px solid #e4e4e7;
          padding-top: 12px;
        }
      </style>
    </head>
    <body>
      <h1>LAEVUS — ${escapeHtml(payload.title)}</h1>
      <div class="meta">
        <strong>Persona:</strong> ${escapeHtml(payload.persona || 'Oracle')} | 
        <strong>Date:</strong> ${escapeHtml(dateStr)} | 
        <strong>Archive ID:</strong> ${Math.random().toString(36).substring(2, 9).toUpperCase()}
      </div>
      <div class="conversation">
        ${formattedConversation}
      </div>
      <div class="footer">
        Generated by LAEVUS Sovereign Portal — Left Hand Products, LLC
      </div>
    </body>
    </html>
  `;

  const blob = new Blob(['\ufeff', docHtml], { type: 'application/msword' });
  const filename = `LAEVUS_${sanitizeFilename(payload.title)}_${Date.now()}.doc`;
  triggerDownload(blob, filename);
};

